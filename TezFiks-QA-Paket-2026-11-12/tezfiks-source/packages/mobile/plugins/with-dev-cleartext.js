/**
 * Expo config plugin: cleartext HTTP only for the development API (plan: "Cleartext HTTP allowed for the dev API").
 *
 * Writes an Android Network Security Config and points the application at it:
 *   - main (release):   HTTPS everywhere, cleartext only for the API host when the API URL is http:// plus the
 *                       emulator/loopback aliases of the developer machine (10.0.2.2, localhost, 127.0.0.1).
 *                       An https API URL (production) allows no cleartext at all.
 *   - debug builds:     cleartext allowed (Metro serves the JS bundle over http from the developer machine,
 *                       which may be a LAN IP on a physical device). Same as React Native's debug manifest default.
 * With a Network Security Config present, Android 7+ (minSdk is 24) ignores android:usesCleartextTraffic, so the
 * attribute is removed from the main manifest to avoid a misleading "true".
 *
 * Options: { apiUrl: string }
 */
const fs = require('node:fs');
const path = require('node:path');

const XML_NAME = 'network_security_config';
const MANIFEST_VALUE = `@xml/${XML_NAME}`;
/** Developer-machine aliases: Android emulator → host, and adb reverse (localhost / 127.0.0.1). */
const DEV_HOST_ALIASES = ['10.0.2.2', 'localhost', '127.0.0.1'];
/** Debug-only source sets of the Expo SDK 58 template. */
const DEBUG_SOURCE_SETS = ['debug', 'debugOptimized'];

/** Host of an http(s) URL without the WHATWG URL implementation; null when not parseable. */
function urlHost(url) {
  const m = /^([a-z][a-z0-9+.-]*):\/\/(?:[^@/?#]*@)?(\[[^\]]+\]|[^:/?#]+)/i.exec(String(url || '').trim());
  return m ? { scheme: m[1].toLowerCase(), host: m[2].toLowerCase().replace(/^\[|\]$/g, '') } : null;
}

/** Hosts that may use cleartext in release builds: none unless the API itself is http://. */
function cleartextHosts(apiUrl) {
  const parsed = urlHost(apiUrl);
  if (!parsed || parsed.scheme !== 'http') return [];
  return [...new Set([parsed.host, ...DEV_HOST_ALIASES])];
}

function escapeXml(s) {
  return String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
}

function networkSecurityXml(hosts) {
  const lines = [
    '<?xml version="1.0" encoding="utf-8"?>',
    '<!-- Generated by @tezfiks/mobile/plugins/with-dev-cleartext: HTTPS only, cleartext just for the dev API hosts. -->',
    '<network-security-config>',
    '  <base-config cleartextTrafficPermitted="false" />',
  ];
  if (hosts.length) {
    lines.push('  <domain-config cleartextTrafficPermitted="true">');
    for (const h of hosts) lines.push(`    <domain includeSubdomains="false">${escapeXml(h)}</domain>`);
    lines.push('  </domain-config>');
  }
  lines.push('</network-security-config>', '');
  return lines.join('\n');
}

function debugNetworkSecurityXml() {
  return [
    '<?xml version="1.0" encoding="utf-8"?>',
    '<!-- Generated by @tezfiks/mobile/plugins/with-dev-cleartext: debug builds load the JS bundle from Metro over http. -->',
    '<network-security-config>',
    '  <base-config cleartextTrafficPermitted="true" />',
    '</network-security-config>',
    '',
  ].join('\n');
}

/** Mutates an Expo AndroidManifest JSON: sets networkSecurityConfig and drops usesCleartextTraffic on <application>. */
function applyToManifest(manifest) {
  const apps = manifest && manifest.manifest && manifest.manifest.application;
  if (!apps || !apps[0]) throw new Error('[with-dev-cleartext] AndroidManifest has no <application>');
  const attrs = (apps[0].$ = apps[0].$ || {});
  attrs['android:networkSecurityConfig'] = MANIFEST_VALUE;
  delete attrs['android:usesCleartextTraffic'];
  return manifest;
}

function writeFile(file, text) {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, text);
}

function withDevCleartext(config, props = {}) {
  const { withAndroidManifest, withDangerousMod } = require('expo/config-plugins');
  const apiUrl = props.apiUrl || (config.extra && config.extra.apiUrl) || '';
  config = withAndroidManifest(config, (cfg) => {
    applyToManifest(cfg.modResults);
    return cfg;
  });
  return withDangerousMod(config, [
    'android',
    async (cfg) => {
      const appSrc = path.join(cfg.modRequest.platformProjectRoot, 'app', 'src');
      writeFile(path.join(appSrc, 'main', 'res', 'xml', `${XML_NAME}.xml`), networkSecurityXml(cleartextHosts(apiUrl)));
      for (const set of DEBUG_SOURCE_SETS) writeFile(path.join(appSrc, set, 'res', 'xml', `${XML_NAME}.xml`), debugNetworkSecurityXml());
      return cfg;
    },
  ]);
}

module.exports = withDevCleartext;
module.exports.urlHost = urlHost;
module.exports.cleartextHosts = cleartextHosts;
module.exports.networkSecurityXml = networkSecurityXml;
module.exports.debugNetworkSecurityXml = debugNetworkSecurityXml;
module.exports.applyToManifest = applyToManifest;
module.exports.DEV_HOST_ALIASES = DEV_HOST_ALIASES;
